// Every post's featured_image must be processed by _scripts/images:
// an entry in _data/images.yml (width, height) and its WebP files on disk.
// _layouts/post.html falls back to a plain <img> otherwise, which loses the
// WebP, the dimensions and the fetch priority on the page's LCP image.
// The data is keyed by path with a leading slash; front matter may omit it.
// Run: node --test '_tests/**/*.test.mjs'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
// WebP widths, as in _scripts/images and _layouts/post.html.
const WIDTHS = [740, 1480];
const FIX = 'run _scripts/images and commit the result';

const unquote = (s) => s.trim().replace(/^(["'])(.*)\1$/, '$2');

// Post files under dir, subfolders included: _posts is an Obsidian vault and
// Jekyll builds posts from its subfolders. Dot folders (.obsidian, .trash)
// are not content.
function postFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    if (e.name.startsWith('.')) return [];
    const abs = join(dir, e.name);
    if (e.isDirectory()) return postFiles(abs);
    return /\.(md|markdown|html)$/.test(e.name) ? [abs] : [];
  });
}

function featuredImages() {
  const dir = join(root, '_posts');
  return postFiles(dir)
    .map((f) => {
      const fm = readFileSync(f, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/);
      const line = fm && fm[1].match(/^featured_image:[ \t]*(.+)$/m);
      return line ? { post: relative(dir, f), image: unquote(line[1]) } : null;
    })
    .filter(Boolean);
}

// The WebP files _scripts/images writes for an image this wide: each of
// WIDTHS it reaches without upscaling, plus one at the image's own width
// when that is below the largest (1000 px -> 740, 1000; 600 px -> 600).
function webpWidths(width) {
  const fit = WIDTHS.filter((w) => w <= width);
  return width < Math.max(...WIDTHS) && !fit.includes(width) ? [...fit, width] : fit;
}

// _data/images.yml is generated by _scripts/images in a fixed shape:
// a quoted path key, then indented width and height.
function imageData() {
  const file = join(root, '_data/images.yml');
  if (!existsSync(file)) return {};
  const data = {};
  let key = null;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const k = line.match(/^"([^"]+)":\s*$/);
    const v = line.match(/^\s+(width|height):\s*(\d+)\s*$/);
    if (k) data[(key = k[1])] = {};
    else if (v && key) data[key][v[1]] = Number(v[2]);
  }
  return data;
}

const images = featuredImages();
const data = imageData();

test('posts with a featured_image exist', () => {
  assert.ok(images.length > 0, 'no featured_image found in _posts/; the test would pass vacuously');
});

for (const { post, image } of images) {
  test(`${post}: ${image} is processed`, () => {
    const path = image.startsWith('/') ? image : `/${image}`;
    const entry = data[path];
    assert.ok(entry, `${path} has no _data/images.yml entry; ${FIX}`);
    assert.ok(entry.width > 0 && entry.height > 0, `${path} entry lacks width/height; ${FIX}`);
    assert.ok(existsSync(join(root, path)), `${path} does not exist`);
    const base = path.replace(/\.[^./]+$/, '');
    for (const w of webpWidths(entry.width)) {
      assert.ok(existsSync(join(root, `${base}-${w}.webp`)), `${base}-${w}.webp is missing; ${FIX}`);
    }
  });
}
